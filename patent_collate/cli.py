#!/usr/bin/env python3
"""CLI entrypoint for the patent-collate pipeline.

Three-stage LLM-powered extraction of structured data from USPTO patent XML tables:
  1. XML → JSON conversion (per-table extraction scripts generated by LLM)
  2. HELM chemistry annotation (nucleotide-level structure strings)
  3. Schema collation (mapping extracted data to user-defined schemas)

Integrated run-all entrypoint:
  Full patent XML -> ScienceAid analysis -> table XML/context -> steps 1-3.
  --input-type full-patent is the new default; use --input-type table for
  previously prepared table XML/context inputs. Standalone steps are unchanged.
  --preprocess-only stops before any ASOClient is created.
"""

import argparse
from copy import copy
from pathlib import Path
import json
import shutil
import re
import sys
import time
from datetime import datetime, timezone


def _record_client_metrics(args, client):
    """Preserve original per-step cost output; collect counters when in run-all."""
    cost = client.calculate_cost()
    print(f"Cost: {cost}")
    receiver = getattr(args, "_metrics_receiver", None)
    if receiver is not None:
        receiver(cost, getattr(client, "usage", {}))


def _aggregate_steps(steps):
    """Aggregate API metrics, retaining an unknown price as unknown."""
    tokens = {"input": 0, "cached_input": 0, "output": 0}
    calls = 0
    estimated_cost = 0.0
    pricing_complete = True
    for step in steps:
        calls += step.get("api_calls", 0)
        for kind in tokens:
            tokens[kind] += step.get("tokens", {}).get(kind, 0)
        if step.get("estimated_cost_usd") is None:
            pricing_complete = False
        else:
            estimated_cost += step["estimated_cost_usd"]
    return {
        "api_calls": calls,
        "tokens": tokens,
        "estimated_cost_usd": round(estimated_cost, 12) if pricing_complete else None,
        "cost_estimate_complete": pricing_complete,
    }


def _capture_step_cost(step, cost, usage, selected_model):
    """Copy actual ASOClient token counts; distinguish unknown prices from $0."""
    calls = int(cost.get("total_calls", 0))
    step["api_calls"] = calls
    step["usage_by_model"] = {}
    step["tokens"] = {"input": 0, "cached_input": 0, "output": 0}
    for model_name, values in usage.items():
        counts = {key: int(values.get(key, 0)) for key in step["tokens"]}
        step["usage_by_model"][model_name] = counts
        for key, value in counts.items():
            step["tokens"][key] += value

    # src.client's internal price table covers only specific model families.
    if calls and selected_model not in cost:
        step["estimated_cost_usd"] = None
        step["cost_note"] = "No pricing rule in src.client for this model"
    else:
        step["estimated_cost_usd"] = round(float(cost.get("total", 0)), 12)


def _save_summary(path, summary):
    temp_path = path.with_name(path.name + ".tmp")
    with temp_path.open("w", encoding="utf-8") as stream:
        json.dump(summary, stream, indent=2, ensure_ascii=False)
        stream.write("\n")
    temp_path.replace(path)


def _print_summary(summary, summary_path):
    def dollars(amount):
        return f"${amount:.9f}" if amount is not None else "N/A (pricing unavailable)"

    print("\n========== EXPERIMENT SUMMARY ==========")
    print(f"Status: {summary['status']}")
    print(f"Model: {summary['model']}")
    print(f"Preprocessing time: {summary['preprocessing']['duration_sec']:.2f} sec")
    for table_name, table in summary["per_table"].items():
        print(f"\n{table_name} [{table['status']}]")
        for step_name, step in table["steps"].items():
            print(
                f"  {step_name}: {step['duration_sec']:.2f} sec | "
                f"Cost: {dollars(step['estimated_cost_usd'])} | "
                f"API calls: {step['api_calls']}"
            )
            print(f"    Output: {step['output']}")
        if "duration_sec" in table:
            print(
                f"  Table total: {table['duration_sec']:.2f} sec | "
                f"Cost: {dollars(table['estimated_cost_usd'])} | "
                f"API calls: {table['api_calls']}"
            )
    print("\nOverall:")
    print(f"  Total time: {summary['total_duration_sec']:.2f} sec")
    print(f"  Total estimated API cost: {dollars(summary['total_estimated_cost_usd'])}")
    print(f"  Total API calls: {summary['total_api_calls']}")
    tokens = summary["total_tokens"]
    print(
        "  Tokens: "
        f"input={tokens['input']}, "
        f"cached_input={tokens['cached_input']}, "
        f"output={tokens['output']}"
    )
    if summary.get("error"):
        print(f"  Error: {summary['error']}")
    print(f"Summary saved to: {summary_path}")
    print("========================================")


def build_table_data(successful_responses, file_to_canonical):
    """Post-process step 1 output into the table_data dict used by later stages."""
    table_data = {}

    for response in successful_responses:
        custom_id = response['custom_id']
        data = json.loads(response['json_output'])

        if custom_id not in table_data:
            table_data[custom_id] = {
                'canonical_link': False,
                'compound_data': {}
            }

        for entry in data.get('entries', []):
            compound_id = entry.get('compound_id')
            if compound_id is None:
                continue

            match = re.search(r'\d+', str(compound_id))
            if match is None:
                continue
            clean_id = match.group()

            if len(clean_id) <= 3:
                continue

            compound_data = entry.get('data')
            if clean_id not in table_data[custom_id]['compound_data']:
                table_data[custom_id]['compound_data'][clean_id] = []
            table_data[custom_id]['compound_data'][clean_id].append(compound_data)

    for duplicate_path, canonical_path in file_to_canonical.items():
        if duplicate_path != canonical_path and canonical_path in table_data:
            table_data[duplicate_path] = {
                'canonical_link': canonical_path,
                'compound_data': {}
            }

    canonical_count = sum(1 for v in table_data.values() if v['canonical_link'] is False)
    duplicate_count = sum(1 for v in table_data.values() if v['canonical_link'] is not False)
    print(f"Table data: {len(table_data)} entries ({canonical_count} canonical, {duplicate_count} duplicates)")
    return table_data


def build_custom_ids_to_annotate(table_data):
    """Determine which compounds in which tables need HELM annotation.

    Groups tables by USPTO patent ID and tracks seen compound IDs per patent
    to avoid re-annotating compounds already present in earlier tables.
    """
    custom_ids = table_data.keys()
    uspto_ids = list(set(re.search(r'(US\w+?)_', cid).group(1) for cid in custom_ids))

    custom_ids_to_annotate = {}
    for uspto_id in uspto_ids:
        seen_mol_ids = set()
        for custom_id in sorted(cid for cid in custom_ids if uspto_id in cid):
            if table_data[custom_id]['canonical_link'] is False:
                new_mol_ids = set()
                for mol_id in table_data[custom_id]['compound_data'].keys():
                    if mol_id not in seen_mol_ids:
                        new_mol_ids.add(mol_id)
                seen_mol_ids.update(new_mol_ids)
                if new_mol_ids:
                    custom_ids_to_annotate[custom_id] = list(new_mol_ids)
            else:
                canonical = table_data[custom_id]['canonical_link']
                seen_mol_ids.update(set(table_data[canonical]['compound_data'].keys()))

    print(f"Will annotate {len(custom_ids_to_annotate)} tables for HELM")
    return custom_ids_to_annotate


def make_client(args):
    from src.client import ASOClient
    return ASOClient(
        model=args.model,
        verbosity="low",
        reasoning_effort=args.reasoning_effort,
        service_tier=args.service_tier if args.service_tier != "none" else None,
        max_workers=args.max_workers,
        debug=args.debug,
        api_key=args.api_key,
        cache_dir=args.cache_dir,
        generated_scripts_dir=getattr(args, "_generated_scripts_dir", None),
    )


def run_step1(args):
    client = make_client(args)
    successful, failed, file_to_canonical = client.agentic_json_conversion(
        input_directory=args.input_dir,
        n_files=args.n_files,
        max_attempts=args.max_attempts,
    )
    print(f"Step 1 complete: {len(successful)} succeeded, {len(failed)} failed")

    table_data = build_table_data(successful, file_to_canonical)

    with open(args.output, 'w') as f:
        json.dump(table_data, f, indent=2)
    print(f"Saved to {args.output}")
    _record_client_metrics(args, client)
    return table_data


def run_step2(args, table_data=None):
    if table_data is None:
        with open(args.table_data, 'r') as f:
            table_data = json.load(f)

    custom_ids_to_annotate = build_custom_ids_to_annotate(table_data)
    client = make_client(args)
    helm_annotations = client.agentic_helm_conversion(
        table_data,
        custom_ids_to_annotate,
        max_attempts=args.max_attempts,
    )

    total_compounds = sum(len(v) for v in helm_annotations.values())
    print(f"Step 2 complete: {total_compounds} compounds annotated across {len(helm_annotations)} tables")

    with open(args.output, 'w') as f:
        json.dump(helm_annotations, f, indent=2)
    print(f"Saved to {args.output}")
    _record_client_metrics(args, client)
    return helm_annotations


def run_step3(args, table_data=None):
    if table_data is None:
        with open(args.table_data, 'r') as f:
            table_data = json.load(f)

    table_data = {k: v for k, v in table_data.items() if v['canonical_link'] is False}

    with open(args.schema, 'r') as f:
        schema_data = json.load(f)

    client = make_client(args)
    collated_data = client.test_and_retry_collate_script(
        table_data,
        schema_data,
        max_attempts=args.max_attempts,
    )

    with open(args.output, 'w') as f:
        json.dump(collated_data, f, indent=2)
    print(f"Step 3 complete. Saved to {args.output}")
    _record_client_metrics(args, client)
    return collated_data


def run_table_pipeline(base_args, table_xml, output_dir, cache_dir, metrics=None):
    """Run the complete Atlas2 Step 1 -> Step 2 -> Step 3 pipeline for one table.

    Each table gets its own input directory, cache, and result files so that
    compound IDs from another table in the same USPTO patent cannot affect
    HELM annotation for this table.
    """
    table_start = time.perf_counter()
    table_xml = Path(table_xml).resolve()
    context_file = table_xml.with_name(table_xml.stem + "_context.txt")
    if not context_file.is_file():
        raise FileNotFoundError(f"Missing context file for {table_xml.name}: {context_file.name}")

    table_output_dir = Path(output_dir).resolve()
    table_input_dir = table_output_dir / "input"
    table_output_dir.mkdir(parents=True, exist_ok=False)
    table_input_dir.mkdir(parents=True, exist_ok=False)

    # Copy only this table pair into the table-specific input directory.
    # Atlas2 therefore sees exactly one table during this complete run.
    shutil.copy2(table_xml, table_input_dir / table_xml.name)
    shutil.copy2(context_file, table_input_dir / context_file.name)

    table_args = copy(base_args)
    table_args.input_dir = str(table_input_dir)
    table_args.cache_dir = str(Path(cache_dir).resolve())
    Path(table_args.cache_dir).mkdir(parents=True, exist_ok=True)

    print(f"\n[Table pipeline] {table_xml.stem}")
    print(f"[Table pipeline] Input: {table_input_dir}")
    print(f"[Table pipeline] Cache: {table_args.cache_dir}")

    if metrics is None:
        metrics = {"steps": {}}
    metrics.update({
        "status": "running",
        "input_dir": str(table_input_dir),
        "cache_dir": table_args.cache_dir,
    })

    def timed_step(step_name, filename, function, **kwargs):
        step = {
            "status": "running",
            "output": str(table_output_dir / filename),
            "duration_sec": 0.0,
            "estimated_cost_usd": None,
            "api_calls": 0,
            "tokens": {"input": 0, "cached_input": 0, "output": 0},
            "usage_by_model": {},
        }

        metrics["steps"][step_name] = step
        table_args.output = step["output"]

        # Directory for LLM-generated scripts (per table and step)
        table_args._generated_scripts_dir = str(
            table_output_dir / "generated_scripts" / step_name
        )

        table_args._metrics_receiver = (
            lambda cost, usage: _capture_step_cost(step, cost, usage, table_args.model)
        )

        start = time.perf_counter()
        try:
            result = function(table_args, **kwargs)
            step["status"] = "completed"
            return result
        except Exception as exc:
            step["status"] = "failed"
            step["error"] = f"{type(exc).__name__}: {exc}"
            raise
        finally:
            step["duration_sec"] = round(time.perf_counter() - start, 4)
            table_args._metrics_receiver = None

    # Same extraction code, same Step 1 -> Step 2 -> Step 3 order.
    try:
        table_data = timed_step("step1", "step1_table_data.json", run_step1)
        timed_step("step2", "step2_helm_annotations.json", run_step2, table_data=table_data)
        timed_step("step3", "step3_collation_results.json", run_step3, table_data=table_data)
        metrics["status"] = "completed"
    except Exception:
        metrics["status"] = "failed"
        raise
    finally:
        metrics["duration_sec"] = round(time.perf_counter() - table_start, 4)
        metrics.update(_aggregate_steps(metrics["steps"].values()))

    print(f"[Table pipeline] Complete: {table_xml.stem}")
    print(f"[Table pipeline] Results: {table_output_dir}")


def run_all(args):
    """Preprocess once, then run a complete independent Atlas2 pipeline per table.

    Full-patent mode:
      1. ScienceAid preprocessing runs once for all requested display tables.
      2. Each generated table XML/context pair is then processed independently
         through Atlas2 Step 1 -> Step 2 -> Step 3.
      3. Results and caches are stored separately for each table.

    Explicit table mode keeps the same per-table independent behavior for all
    XML/context pairs found in --input-dir.
    """
    pipeline_start = time.perf_counter()
    input_type = args.input_type
    if input_type == "table" and args.tables is not None:
        raise ValueError("--tables is only supported with --input-type full-patent")
    if input_type == "table" and args.preprocess_only:
        raise ValueError("--preprocess-only requires --input-type full-patent")
    if args.tables is not None and any(n < 1 or n > 99999 for n in args.tables):
        raise ValueError("--tables must contain positive integers from 1 to 99999")
    if args.n_files is not None:
        raise ValueError(
            "--n-files is not supported by per-table run-all. "
            "Use --tables to choose display tables in full-patent mode."
        )

    input_dir = Path(args.input_dir).expanduser().resolve()
    output_dir = Path(args.output_dir).expanduser().resolve()
    if not input_dir.is_dir():
        raise FileNotFoundError(f"Input directory does not exist: {input_dir}")
    if output_dir.exists():
        raise FileExistsError(
            f"Output directory already exists: {output_dir}\n"
            "Use a NEW --output-dir. Existing results are not overwritten."
        )
    if output_dir == input_dir or input_dir in output_dir.parents:
        raise ValueError("Keep --output-dir outside the input directory")

    # Validate the schema before any paid extraction work, not only at step 3.
    schema_path = None
    if not args.preprocess_only and not args.schema:
        raise ValueError("--schema is required unless --preprocess-only is used")
    if args.schema:
        schema_path = Path(args.schema).expanduser().resolve()
        if not schema_path.is_file():
            raise FileNotFoundError(f"Schema file does not exist: {schema_path}")
        with schema_path.open("r", encoding="utf-8") as stream:
            json.load(stream)

    if input_type == "full-patent":
        from src.prepare_inputs import prepare_inputs
    else:
        xml_files = sorted(path for path in input_dir.glob("*.xml") if path.is_file())
        if not xml_files:
            raise ValueError(f"No .xml table files in: {input_dir}")
        missing_context = [
            path.with_name(path.stem + "_context.txt").name
            for path in xml_files
            if not path.with_name(path.stem + "_context.txt").is_file()
        ]
        if missing_context:
            raise FileNotFoundError("Missing context file(s): " + ", ".join(missing_context))

    base_args = copy(args)
    base_args.schema = str(schema_path) if schema_path is not None else None
    output_dir.mkdir(parents=True, exist_ok=False)

    summary_path = output_dir / "experiment_summary.json"
    summary = {
        "status": "running",
        "created_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "model": args.model,
        "input_type": input_type,
        "input_dir": str(input_dir),
        "schema": str(schema_path) if schema_path else None,
        "output_dir": str(output_dir),
        "settings": {
            "reasoning_effort": args.reasoning_effort,
            "service_tier": args.service_tier,
            "max_workers": args.max_workers,
            "max_attempts": args.max_attempts,
            "preprocess_only": args.preprocess_only,
            "requested_tables": args.tables,
        },
        "preprocessing": {"duration_sec": 0.0, "prepared_input_dir": None},
        "per_table": {},
        "total_duration_sec": 0.0,
        "total_estimated_cost_usd": 0.0,
        "total_api_calls": 0,
        "total_tokens": {"input": 0, "cached_input": 0, "output": 0},
        "cost_estimate_complete": True,
    }

    try:
        if input_type == "full-patent":
            print("[Preprocessing] Full patent XML -> ScienceAid -> table XML/context")
            preprocess_start = time.perf_counter()
            try:
                prepared_dir = Path(prepare_inputs(
                    input_dir=input_dir,
                    output_dir=output_dir / "preprocessing",
                    tables=args.tables,
                    verbose=args.debug,
                )).resolve()
            finally:
                summary["preprocessing"]["duration_sec"] = round(
                    time.perf_counter() - preprocess_start, 4
                )
            summary["preprocessing"]["prepared_input_dir"] = str(prepared_dir)
            print(f"[Preprocessing] Complete. Prepared Atlas2 inputs: {prepared_dir}")
            if args.preprocess_only:
                print("Preprocessing-only complete. Steps 1-3 were NOT run; no LLM API was called.")
                print(f"Results in {output_dir}/")
                summary["status"] = "completed"
                return prepared_dir
            xml_files = sorted(path for path in prepared_dir.glob("*.xml") if path.is_file())
        else:
            prepared_dir = input_dir
            summary["preprocessing"]["prepared_input_dir"] = str(prepared_dir)
            print(f"[Input] Existing table XML/context: {prepared_dir}")
            xml_files = sorted(path for path in prepared_dir.glob("*.xml") if path.is_file())

        if not xml_files:
            raise ValueError(f"No prepared table XML files found in: {prepared_dir}")

        print(f"[Extraction] Running {len(xml_files)} independent table pipeline(s).")
        print("[Extraction] Each table runs Atlas2 Step 1 -> Step 2 -> Step 3 separately.")
        print("[Extraction] LLM API calls may incur charges.")

        tables_output_dir = output_dir / "tables"
        tables_output_dir.mkdir(parents=True, exist_ok=False)

        # Same per-table cache separation as before.
        if args.cache_dir is None:
            cache_parent = output_dir / "cache"
        else:
            cache_parent = Path(args.cache_dir).expanduser().resolve()
        cache_parent.mkdir(parents=True, exist_ok=True)

        completed = []
        for table_xml in xml_files:
            table_name = table_xml.stem
            table_output_dir = tables_output_dir / table_name
            table_cache_dir = cache_parent / table_name
            table_metrics = {"status": "running", "steps": {}}
            summary["per_table"][table_name] = table_metrics
            run_table_pipeline(
                base_args=base_args,
                table_xml=table_xml,
                output_dir=table_output_dir,
                cache_dir=table_cache_dir,
                metrics=table_metrics,
            )
            completed.append(table_name)

        print("\nPipeline complete.")
        print(f"Completed {len(completed)} independent table pipeline(s):")
        for table_name in completed:
            print(f"  - {table_name}")
        print(f"Results in {tables_output_dir}/")
        summary["status"] = "completed"
    except Exception as exc:
        summary["status"] = "failed"
        summary["error"] = f"{type(exc).__name__}: {exc}"
        for table_metrics in summary["per_table"].values():
            if table_metrics.get("status") == "running":
                table_metrics["status"] = "failed"
        raise
    finally:
        summary["total_duration_sec"] = round(time.perf_counter() - pipeline_start, 4)
        totals = _aggregate_steps(
            step
            for table in summary["per_table"].values()
            for step in table["steps"].values()
        )
        summary["total_estimated_cost_usd"] = totals["estimated_cost_usd"]
        summary["total_api_calls"] = totals["api_calls"]
        summary["total_tokens"] = totals["tokens"]
        summary["cost_estimate_complete"] = totals["cost_estimate_complete"]
        _save_summary(summary_path, summary)
        _print_summary(summary, summary_path)

def main():
    parser = argparse.ArgumentParser(
        description="Patent table extraction pipeline",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )

    # Global arguments
    parser.add_argument("--model", default="gpt-5-mini")
    parser.add_argument("--api-key", default=None, help="OpenAI API key (or set OPENAI_API_KEY)")
    parser.add_argument("--reasoning-effort", default="medium", choices=["low", "medium", "high"])
    parser.add_argument("--service-tier", default="flex", choices=["flex", "default", "none"])
    parser.add_argument("--max-workers", type=int, default=50)
    parser.add_argument("--max-attempts", type=int, default=5)
    parser.add_argument("--debug", action="store_true")
    parser.add_argument("--cache-dir", default=None, help="Override cache directory")

    subparsers = parser.add_subparsers(dest="command", required=True)

    # Step 1
    p1 = subparsers.add_parser("step1", help="XML → JSON table extraction")
    p1.add_argument("--input-dir", required=True, help="Directory containing patent XML files")
    p1.add_argument("--output", default="step1_table_data.json")
    p1.add_argument("--n-files", type=int, default=None, help="Limit number of files to process")

    # Step 2
    p2 = subparsers.add_parser("step2", help="HELM chemistry annotation")
    p2.add_argument("--table-data", required=True, help="Path to step 1 output JSON")
    p2.add_argument("--output", default="step2_helm_annotations.json")

    # Step 3
    p3 = subparsers.add_parser("step3", help="Schema collation")
    p3.add_argument("--table-data", required=True, help="Path to step 1 output JSON")
    p3.add_argument("--schema", required=True, help="Path to schema JSON file")
    p3.add_argument("--output", default="step3_collation_results.json")

    # Run all: integrate ScienceAid preprocessing without modifying the stages.
    pa = subparsers.add_parser("run-all", help="ScienceAid preprocessing + Atlas2 steps 1-3")
    pa.add_argument("--input-dir", required=True, help="Input folder; full patent XML by default")
    pa.add_argument("--input-type", choices=["full-patent", "table"], default="full-patent",
                    help="full-patent (default): prepare XML/context; table: use existing pairs")
    pa.add_argument("--tables", type=int, nargs="+", default=None,
                    help="Display table numbers, e.g. 20 40; full-patent mode only; omitted: all")
    pa.add_argument("--preprocess-only", action="store_true",
                    help="Prepare inputs and stop BEFORE any LLM API calls; no schema needed")
    pa.add_argument("--schema", default=None, help="Step 3 schema JSON; required unless --preprocess-only")
    pa.add_argument("--output-dir", required=True, help="NEW directory for this run; must not already exist")
    pa.add_argument("--n-files", type=int, default=None,
                    help="Not supported in per-table run-all; use --tables instead")

    args = parser.parse_args()

    dispatch = {
        "step1": run_step1,
        "step2": run_step2,
        "step3": run_step3,
        "run-all": run_all,
    }
    if args.command == "run-all":
        try:
            run_all(args)
        except (OSError, ValueError) as exc:
            if args.debug:
                raise
            parser.exit(1, f"ERROR: {exc}\n")
    else:
        dispatch[args.command](args)


if __name__ == "__main__":
    main()
